const LEGACY_COMPATIBILITY_MATERIAL_KEY_MAP = {
  "1StarWeaponFodder": "OneStarWeaponFodder",
  "2StarWeaponFodder": "TwoStarWeaponFodder",
  "3StarWeaponFodder": "ThreeStarWeaponFodder",
  "KnightsOfFavoniusHandbook5ThEdition": "KnightsOfFavoniusHandbook5thEdition",
} as const;

const NORMALIZED_LABEL_MAP = new Map<string, string>(
  Object.entries(ENHANCEMENT_MATERIAL_KEY_MAP).map(([label, key]) => [normalizeMaterialLookupKey(label), key]),
);
const NORMALIZED_LEGACY_ALIAS_MAP = new Map<string, string>(
  Object.entries(LEGACY_COMPATIBILITY_MATERIAL_KEY_MAP).map(([alias, key]) => [normalizeMaterialLookupKey(alias), key]),
);

function normalizeMaterialLookupKey(value: string): string {
  return value.replace(/[^A-Za-z0-9]/g, "").toLowerCase();
}

function toPascalCaseIrminsulKey(value: string): string {
  return value
    .replace(/['’]/g, "")
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

export function resolveInventoryMaterialKey(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) {
    return trimmed;
  }

  const explicit = NORMALIZED_LABEL_MAP.get(normalizeMaterialLookupKey(trimmed));
  if (explicit) {
    return explicit;
  }

  const generatedKey = toPascalCaseIrminsulKey(trimmed);
  return LEGACY_COMPATIBILITY_MATERIAL_KEY_MAP[generatedKey as keyof typeof LEGACY_COMPATIBILITY_MATERIAL_KEY_MAP] ?? generatedKey;
}

export function isLegacyCompatibilityMaterialKey(materialKey: string): boolean {
  return Object.values(LEGACY_COMPATIBILITY_MATERIAL_KEY_MAP).includes(
    materialKey as (typeof LEGACY_COMPATIBILITY_MATERIAL_KEY_MAP)[keyof typeof LEGACY_COMPATIBILITY_MATERIAL_KEY_MAP],
  );
}

export function resolveExistingMaterialKey<
  TMaterial extends {
    key: string;
    displayName: string;
  },
>(value: string, materials: Record<string, TMaterial>): string | undefined {
  const trimmed = value.trim();
  if (!trimmed) {
    return undefined;
  }

  const byDisplayName = Object.values(materials).find(
    (material) => normalizeMaterialLookupKey(material.displayName) === normalizeMaterialLookupKey(trimmed),
  );
  if (byDisplayName) {
    return byDisplayName.key;
  }

  const generatedKey = resolveInventoryMaterialKey(trimmed);
  if (materials[generatedKey]) {
    return generatedKey;
  }

  const legacyKey = NORMALIZED_LEGACY_ALIAS_MAP.get(normalizeMaterialLookupKey(trimmed));
  if (legacyKey && materials[legacyKey]) {
    return legacyKey;
  }

  return undefined;
}
